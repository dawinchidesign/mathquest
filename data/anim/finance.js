// Баға белгісі (ценник)
const priceTag = (g, x, y, text, o = {}) => {
  const grp = g.group({ hide: true });
  g.into(grp, () => {
    g.path(`M${x} ${y} L${x + 30} ${y - 34} L${x + 190} ${y - 34} L${x + 190} ${y + 34} L${x + 30} ${y + 34} Z`, { fill: o.fill || 'goldsoft', stroke: o.stroke || 'gold', sw: 3, now: true });
    g.circle(x + 30, y, 7, { fill: 'sheet', cls: 's-gold', now: true });
    g.text(x + 112, y + 1, text, { size: o.size || 30, math: true, bold: true, now: true });
  });
  grp.origin(x + 95, y); grp.st.op = 1; grp.apply(); grp.in(400);
  return grp;
};
// Чек (түбіртек)
const receipt = (g, x, y, w, h) => {
  let d = `M${x} ${y} L${x + w} ${y} L${x + w} ${y + h}`;
  for (let i = 0; i < 10; i++) d += ` L${x + w - (i + .5) * w / 10} ${y + h - 10} L${x + w - (i + 1) * w / 10} ${y + h}`;
  return g.path(d + ' Z', { fill: 'sheet', stroke: 'line', sw: 2, fade: true });
};

